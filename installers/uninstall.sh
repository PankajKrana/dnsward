#!/bin/sh
# Removes AdBlock from Linux or macOS and restores the previous DNS settings.
#
#   ./installers/uninstall.sh            keep the configuration file
#   ./installers/uninstall.sh --purge    also delete the configuration
set -eu

PURGE=""
[ "${1:-}" = "--purge" ] && PURGE="--purge"

say()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mwarning:\033[0m %s\n' "$*" >&2; }
if [ "$(id -u)" -eq 0 ]; then SUDO=""; else SUDO="sudo"; fi

ADBLOCK="$(command -v adblock 2>/dev/null || true)"
[ -n "$ADBLOCK" ] || { [ -x /usr/local/bin/adblock ] && ADBLOCK=/usr/local/bin/adblock; } || true

if [ -n "$ADBLOCK" ]; then
    say "Running $ADBLOCK uninstall"
    # Restores DNS from the recorded backup, removes the service, data and binary.
    $SUDO "$ADBLOCK" uninstall --yes $PURGE && exit 0
    warn "built-in uninstall failed; continuing with manual cleanup"
fi

# Manual cleanup (binary missing or broken).
case "$(uname -s)" in
Linux)
    $SUDO systemctl disable --now adblock.service 2>/dev/null || true
    $SUDO rm -f /etc/systemd/system/adblock.service
    $SUDO systemctl daemon-reload || true
    if [ -f /etc/systemd/resolved.conf.d/90-adblock.conf ]; then
        $SUDO rm -f /etc/systemd/resolved.conf.d/90-adblock.conf
        $SUDO systemctl restart systemd-resolved.service || true
    fi
    if [ -f /etc/NetworkManager/conf.d/90-adblock.conf ]; then
        $SUDO rm -f /etc/NetworkManager/conf.d/90-adblock.conf
        $SUDO systemctl reload NetworkManager.service || true
    fi
    if grep -q "Generated by AdBlock" /etc/resolv.conf 2>/dev/null; then
        if [ -e /run/systemd/resolve/stub-resolv.conf ]; then
            $SUDO ln -sf /run/systemd/resolve/stub-resolv.conf /etc/resolv.conf
        else
            warn "/etc/resolv.conf still points to AdBlock; restore it manually (e.g. 'nameserver 1.1.1.1')"
        fi
    fi
    $SUDO rm -rf /var/lib/adblock /usr/local/share/adblock
    [ -n "$PURGE" ] && $SUDO rm -rf /etc/adblock
    for d in /etc/opt/chrome/native-messaging-hosts /etc/chromium/native-messaging-hosts \
             /etc/opt/edge/native-messaging-hosts /usr/lib/mozilla/native-messaging-hosts \
             /usr/lib64/mozilla/native-messaging-hosts; do
        $SUDO rm -f "$d/com.adblock.native.json"
    done
    id -u adblock >/dev/null 2>&1 && $SUDO userdel adblock 2>/dev/null || true
    ;;
Darwin)
    $SUDO launchctl bootout system/com.adblock.daemon 2>/dev/null || true
    $SUDO rm -f /Library/LaunchDaemons/com.adblock.daemon.plist /etc/newsyslog.d/adblock.conf
    # Revert any network service still pointing at the local resolver to DHCP.
    networksetup -listallnetworkservices | tail -n +2 | sed 's/^\*//' | while IFS= read -r svc; do
        if networksetup -getdnsservers "$svc" 2>/dev/null | grep -qx "127.0.0.1"; then
            $SUDO networksetup -setdnsservers "$svc" Empty
        fi
    done
    $SUDO dscacheutil -flushcache; $SUDO killall -HUP mDNSResponder 2>/dev/null || true
    $SUDO rm -rf "/Library/Application Support/AdBlock/data" /Library/Logs/AdBlock /usr/local/share/adblock
    $SUDO rm -f "/Library/Application Support/AdBlock/system-state.json"
    [ -n "$PURGE" ] && $SUDO rm -rf "/Library/Application Support/AdBlock"
    for d in "/Library/Google/Chrome/NativeMessagingHosts" "/Library/Application Support/Chromium/NativeMessagingHosts" \
             "/Library/Microsoft/Edge/NativeMessagingHosts" "/Library/Application Support/Mozilla/NativeMessagingHosts"; do
        $SUDO rm -f "$d/com.adblock.native.json"
    done
    $SUDO dscl . -delete /Users/_adblock 2>/dev/null || true
    $SUDO dscl . -delete /Groups/_adblock 2>/dev/null || true
    ;;
esac
$SUDO rm -f /usr/local/bin/adblock /usr/local/bin/adblock-native-host
say "AdBlock removed"
